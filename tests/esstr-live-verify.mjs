#!/usr/bin/env node
// ESSTR live verification: runs the shared vector battery inside the REAL
// Adobe engine through COM Tool V2 and compares each engine
// result against the Node-side core (which npm test has already validated
// against Node's native String trim methods). Strings are hex-transported
// (code units) so NULs/surrogates survive JSON untouched.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createLegacyComToolV2Runner } from '../../extendscript-toolchain/src/comtool-v2-compat.mjs';

var ROOT = dirname(fileURLToPath(import.meta.url));
var PROJECT = join(ROOT, '..');
var DIST = join(PROJECT, 'dist');
var VENDOR = join(DIST, 'vendor-esstr.js');
var COM = createLegacyComToolV2Runner();
process.on('exit', function () { try { COM.close(); } catch (ignore) {} });

if (!existsSync(VENDOR)) {
  console.error('live-verify: build first (npm run build) - ' + VENDOR + ' missing');
  process.exit(1);
}

var core = await import(pathToFileURL(join(DIST, 'esstr-core.esm.mjs')).href);

// Bundle tests/callbacks.ts to ESM so Node runs the same vector logic.
var CB_BUNDLE = join(ROOT, '.esstr-callbacks.bundle.mjs');
execFileSync(process.execPath, [esbuildBin(), join(ROOT, 'callbacks.ts'),
  '--bundle', '--outfile=' + CB_BUNDLE,
  '--format=esm', '--platform=node', '--target=es2019',
  '--log-level=warning'], { stdio: 'inherit' });
var cbs = await import(pathToFileURL(CB_BUNDLE).href);

var V_BUNDLE = join(ROOT, '.esstr-vectors.bundle.mjs');
execFileSync(process.execPath, [esbuildBin(), join(ROOT, 'vectors.ts'),
  '--bundle', '--outfile=' + V_BUNDLE,
  '--format=esm', '--platform=node', '--target=es2019',
  '--log-level=warning'], { stdio: 'inherit' });
var vecs = await import(pathToFileURL(V_BUNDLE).href);

var vectors = vecs.VECTORS;
var runVector = cbs.runVector;

// ---- hex transport: code units survive JSON (NUL, surrogates) --------------
function hex(s) {
  if (typeof s !== 'string') { return '~' + String(s); }
  var out = '', i, c;
  for (i = 0; i < s.length; i++) {
    c = s.charCodeAt(i).toString(16);
    while (c.length < 4) { c = '0' + c; }
    out += c;
  }
  return out;
}
function encodeVec(v) {
  // Non-string inputs (numbers/null/undefined coercion probes) are marked:
  //   ~n<number> | ~b<0|1> | ~null | ~undefined
  var input;
  if (typeof v.input === 'string') { input = hex(v.input); }
  else if (v.input === null) { input = '~null'; }
  else if (v.input === void 0) { input = '~undefined'; }
  else if (typeof v.input === 'boolean') { input = '~b' + (v.input ? '1' : '0'); }
  else { input = '~n' + String(v.input); }
  return { desc: v.desc, input: input, op: v.op };
}

// Node-side expected results
var nodeResults = [];
for (var vi = 0; vi < vectors.length; vi++) {
  var r = runVector(vectors[vi], core);
  nodeResults.push({ ok: r.ok, result: r.ok ? hex(r.result) : 'TypeError' });
}

// ---- emit the engine probe ---------------------------------------------------
var probeDir = join(process.env.TEMP || '', 'esstr-live');
mkdirSync(probeDir, { recursive: true });
var probePath = join(probeDir, 'esstr-live-battery.jsx');
var vendorForProbe = VENDOR.replace(/\\/g, '/');
var vectorsJson = JSON.stringify(vectors.map(encodeVec));

var probeSrc = [
  '#target illustrator',
  '// generated by tests/esstr-live-verify.mjs - do not edit',
  '$.evalFile(File("' + vendorForProbe + '"));',
  'var esstrVectors = ' + vectorsJson + ';',
  'function esstrHexToStr(h) {',
  '  var out = [], i;',
  '  for (i = 0; i < h.length; i += 4) {',
  '    out[out.length] = String.fromCharCode(parseInt(h.substring(i, i + 4), 16));',
  '  }',
  '  return out.join("");',
  '}',
  'function esstrStrToHex(s) {',
  '  var out = [], i, c;',
  '  for (i = 0; i < s.length; i++) {',
  '    c = s.charCodeAt(i).toString(16);',
  '    while (c.length < 4) { c = "0" + c; }',
  '    out[out.length] = c;',
  '  }',
  '  return out.join("");',
  '}',
  '  function esstrDecodeIn(inp) {',
  '    if (inp === "~null") { return null; }',
  '    if (inp === "~undefined") { return void 0; }',
  '    if (inp.substring(0, 2) === "~b") { return inp === "~b1"; }',
  '    if (inp.substring(0, 2) === "~n") { return Number(inp.substring(2)); }',
  '    return esstrHexToStr(inp);',
  '  }',
  '  // The COM session persists $.global across evals: stale wrappers from an',
  '  // earlier vendor load survive the gap-fill footer (which only installs when',
  '  // absent). Force-replace so THIS bundle is what the wrapper tests exercise.',
  '  ESSTR.install({ forceReplace: true });',
  'var esstrResults = [];',
  'var esstrV, esstrR, esstrI;',
  'for (esstrI = 0; esstrI < esstrVectors.length; esstrI++) {',
  '  esstrV = esstrVectors[esstrI];',
  '  var esstrIn = esstrDecodeIn(esstrV.input);',
  '  try {',
  '    if (esstrV.op === "trim") { esstrR = ESSTR.trim(esstrIn); }',
  '    else if (esstrV.op === "trimLeft") { esstrR = ESSTR.trimLeft(esstrIn); }',
  '    else if (esstrV.op === "trimRight") { esstrR = ESSTR.trimRight(esstrIn); }',
  '    else if (esstrV.op === "trimStart") { esstrR = ESSTR.trimStart(esstrIn); }',
  '    else { esstrR = ESSTR.trimEnd(esstrIn); }',
  '    esstrResults[esstrResults.length] = { desc: esstrV.desc, ok: true, result: esstrStrToHex(esstrR) };',
  '    } catch (e) {',
  '      esstrResults[esstrResults.length] = { desc: esstrV.desc, ok: false,',
  '        result: e instanceof TypeError ? "TypeError" : String(e) };',
  '    }',
  '}',
  '// prototype wrapper semantics after install',
  'var esstrW = {};',
  'var esstrProto = String.prototype;',
  'esstrW.protoTypes = { trim: typeof esstrProto.trim, trimLeft: typeof esstrProto.trimLeft,',
  '  trimRight: typeof esstrProto.trimRight, trimStart: typeof esstrProto.trimStart, trimEnd: typeof esstrProto.trimEnd };',
  'try { esstrW.trimProto = esstrStrToHex("  x  ".trim()); } catch (e) { esstrW.trimProto = "ERR " + e; }',
  'try { esstrW.leftProto = esstrStrToHex("  x  ".trimLeft()); } catch (e) { esstrW.leftProto = "ERR " + e; }',
  'try { esstrW.rightProto = esstrStrToHex("  x  ".trimRight()); } catch (e) { esstrW.rightProto = "ERR " + e; }',
  'try { esstrW.startProto = esstrStrToHex("  x  ".trimStart()); } catch (e) { esstrW.startProto = "ERR " + e; }',
  'try { esstrW.endProto = esstrStrToHex("  x  ".trimEnd()); } catch (e) { esstrW.endProto = "ERR " + e; }',
  'try { esstrW.callNumber = esstrStrToHex(esstrProto.trim.call(123)); } catch (e) { esstrW.callNumber = "ERR " + e; }',
  'try { esstrW.callNull = esstrProto.trim.call(null); esstrW.callNull = "NO THROW"; } catch (e) { esstrW.callNull = "TypeError"; }',
  'try { esstrW.nulKept = esstrStrToHex(" \\u0000 ".trim()); } catch (e) { esstrW.nulKept = "ERR " + e; }',
  'try { esstrW.feffStripped = esstrStrToHex("\\ufeffq\\ufeff".trim()); } catch (e) { esstrW.feffStripped = "ERR " + e; }',
  'esstrW.caps = ESSTR.capabilities();',
  'try { ESSTR.install(); esstrW.installAgain = "ok"; } catch (e) { esstrW.installAgain = "ERR " + e; }',
  'try { ESSTR.install({ forceReplace: true }); esstrW.forceReplace = "ok"; } catch (e) { esstrW.forceReplace = "ERR " + e; }',
  'var esstrReport = { engine: $.version, host: app.name + " " + app.version, results: esstrResults, w: esstrW };',
  'esstrReport;'
].join('\n');
writeFileSync(probePath, probeSrc);

console.log('live-verify: running ' + vectors.length + ' vectors in Illustrator...');
var pyOut;
try {
  // --launch attaches to a running instance and only starts Illustrator when
  // none exists; it never kills or restarts a live session.
  pyOut = COM.runText(
    ['eval', '--file', probePath.replace(/\\/g, '/'), '--launch'],
    { timeoutMs: 300000 }
  );
} catch (e) {
  console.error('live-verify: COM tool failed: ' + String((e.stdout || e.message) + '').slice(0, 2000));
  process.exit(1);
}

var env;
try { env = JSON.parse(pyOut.trim()); } catch (e) { console.error('live-verify: tool output not JSON: ' + pyOut.slice(0, 500)); process.exit(1); }
if (!env.ok || !env.result) {
  console.error('live-verify: tool/engine error: ' + JSON.stringify(env).slice(0, 1500));
  process.exit(1);
}
var report = env.result.result || env.result;

var failures = 0;
for (var i = 0; i < vectors.length; i++) {
  var got = report.results[i];
  var want = nodeResults[i];
  var ok = got.ok === want.ok && got.result === want.result;
  if (!ok) {
    failures++;
    console.error('  FAIL ' + got.desc + ': engine=' + got.result + ' node=' + want.result);
  }
}
console.log('live-verify: ' + (vectors.length - failures) + '/' + vectors.length + ' vectors match in engine ' + report.engine);

var extraFailures = 0;
function x(name, got, want) {
  var g = JSON.stringify(got);
  var w = JSON.stringify(want);
  if (g === w) { console.log('  ok   ' + name + ' = ' + g); }
  else { extraFailures++; console.error('  FAIL ' + name + ': engine=' + g + ' expected=' + w); }
}
x('protoTypes.trim', report.w.protoTypes.trim, 'function');
x('protoTypes.trimEnd', report.w.protoTypes.trimEnd, 'function');
x('trimProto', report.w.trimProto, hex('x'));
x('leftProto', report.w.leftProto, hex('x  '));
x('rightProto', report.w.rightProto, hex('  x'));
x('startProto', report.w.startProto, hex('x  '));
x('endProto', report.w.endProto, hex('  x'));
x('callNumber -> "123"', report.w.callNumber, hex('123'));
x('callNull (ES3: .call(null) binds GLOBAL, so the wrapper never sees null; facade guard is what throws)', report.w.callNull, 'NO THROW');
x('NUL kept by trim', report.w.nulKept, hex('\u0000'));
x('FEFF stripped', report.w.feffStripped, hex('q'));
x('caps.missing is 0 after forceReplace', report.w.caps.missing.length, 0);
x('installAgain', report.w.installAgain, 'ok');
x('forceReplace', report.w.forceReplace, 'ok');

if (failures > 0 || extraFailures > 0) {
  console.error('live-verify: ' + failures + ' vector failure(s), ' + extraFailures + ' extra failure(s)');
  process.exit(1);
}
console.log('live-verify: all vectors + wrappers verified in the live engine');

function esbuildBin() {
  var direct = join(PROJECT, 'node_modules', 'esbuild', 'bin', 'esbuild');
  if (existsSync(direct)) { return direct; }
  var cacheDirs = [
    join(process.env.LOCALAPPDATA || '', 'npm-cache', '_npx'),
    join(process.env.USERPROFILE || '', 'AppData', 'Local', 'npm-cache', '_npx')
  ];
  for (var c = 0; c < cacheDirs.length; c++) {
    try {
      var entries = readdirSync(cacheDirs[c]);
      for (var j = 0; j < entries.length; j++) {
        var p = join(cacheDirs[c], entries[j], 'node_modules', 'esbuild', 'bin', 'esbuild');
        if (existsSync(p)) { return p; }
      }
    } catch (ignore) {}
  }
  return 'npx esbuild';
}
