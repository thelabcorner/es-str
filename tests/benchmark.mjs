#!/usr/bin/env node
// ESSTR live benchmark: measures the bundled library against (a) the stock
// extendscript-es5-shim regex implementation and (b) a hand-rolled charCodeAt
// scan — in the REAL Adobe engine via ILLUSTRATOR_COM_TOOL.py.
// Lanes: "repeat" (same string, memo hit — the real-world case) and "fresh"
// (distinct strings, memo miss). Inputs bounded to short strings: the stock
// shim's regex WEDGES the engine from ~200 chars up (verified live).
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as ESARR from 'esarr';

var ROOT = dirname(fileURLToPath(import.meta.url));
var PROJECT = join(ROOT, '..');
var DIST = join(PROJECT, 'dist');
var VENDOR = process.env.ESSTR_VENDOR_PATH || join(DIST, 'vendor-esstr.js');
var TOOL = 'C:/Program Files/Adobe/Adobe Illustrator 2026/Presets/en_US/Scripts/agent-skills/illustrator-com-automation-skill/comtool/ILLUSTRATOR_COM_TOOL.py';

if (!existsSync(VENDOR)) { console.error('benchmark: build first (npm run build)'); process.exit(1); }
if (!existsSync(TOOL)) { console.error('benchmark: COM tool not found'); process.exit(1); }

var probeDir = join(process.env.TEMP || '', 'esstr-bench');
mkdirSync(probeDir, { recursive: true });
var probePath = join(probeDir, 'esstr-bench-battery.jsx');
var vendorForProbe = VENDOR.replace(/\\/g, '/');

var probeSrc = [
  '#target illustrator',
  '// generated by tests/benchmark.mjs - do not edit',
  '$.evalFile(File("' + vendorForProbe + '"));',
  'ESSTR.install({ forceReplace: true });',
  'function bShimTrim(s) { return s.replace(/^[\\s\\uFEFF\\xA0]+|[\\s\\uFEFF\\xA0]+$/g, ""); }',
  'function bIsWs(c) {',
  '  if (c === 32 || c === 9 || c === 10 || c === 13 || c === 11 || c === 12 || c === 160) { return true; }',
  '  if (c < 256) { return false; }',
  '  if (c === 0x1680) { return true; }',
  '  if (c === 0x2028) { return true; }',
  '  if (c === 0x2029) { return true; }',
  '  if (c === 0x202F) { return true; }',
  '  if (c === 0x205F) { return true; }',
  '  if (c === 0x3000) { return true; }',
  '  if (c === 0xFEFF) { return true; }',
  '  return c >= 0x2000 && c <= 0x200A;',
  '}',
  'function bHandTrim(s) {',
  '  var len = s.length, st = 0, en = len - 1;',
  '  while (st < len && bIsWs(s.charCodeAt(st))) { st++; }',
  '  while (en >= st && bIsWs(s.charCodeAt(en))) { en--; }',
  '  return s.substring(st, en + 1);',
  '}',
  'var bInputs = {',
  '  plain: "the quick brown fox jumps over the lazy dog",',
  '  padded: "  \\tthe quick brown fox jumps over the lazy dog\\r\\n ",',
  '  allws: " \\t\\n\\r\\u000b\\u000c\\u00a0\\u3000\\u2003\\ufeff ",',
  '  uni: "\\u3000\\u2003x\\u00a0\\u2028\\u3000"',
  '};',
  'var bNames = ["plain", "padded", "allws", "uni"];',
  'function bTime(fn) {',
  '  var best = 1e15, i, d, v = 0;',
  '  for (i = 0; i < 2; i++) { v = fn(); }',
  '  for (i = 0; i < 9; i++) {',
  '    $.hiresTimer;',
  '    fn();',
  '    d = $.hiresTimer;',
  '    if (d > 0 && d < best) { best = d; }',
  '    v += 1;',
  '  }',
  '  return best;',
  '}',
  'var bFreshPool = [];',
  'var bK;',
  'for (bK = 0; bK < 40; bK++) {',
  '  bFreshPool[bFreshPool.length] = (bK % 2 === 0 ? "  " : "\\t ") + bInputs.padded + "\\r\\n";',
  '}',
  'var bOut = [];',
  'var bI;',
  'for (bI = 0; bI < bNames.length; bI++) {',
  '  var bNm = bNames[bI];',
  '  var bS = bInputs[bNm];',
  '  ESSTR.clearMemo();',
  '  var oursRepeat = bTime(function () { return ESSTR.trim(bS); });',
  '  var oursFresh = bTime(function () {',
  '    var x = 0, q;',
  '    for (q = 0; q < 40; q++) { x += ESSTR.trim(bFreshPool[q]).length; }',
  '    return x;',
  '  });',
  '  var shim40 = bTime(function () {',
  '    var x = 0, q;',
  '    for (q = 0; q < 40; q++) { x += bShimTrim(bFreshPool[q]).length; }',
  '    return x;',
  '  });',
  '  var hand40 = bTime(function () {',
  '    var x = 0, q;',
  '    for (q = 0; q < 40; q++) { x += bHandTrim(bFreshPool[q]).length; }',
  '    return x;',
  '  });',
  '  var shim = bTime(function () { return bShimTrim(bS); });',
  '  var hand = bTime(function () { return bHandTrim(bS); });',
  '  bOut[bOut.length] = { name: bNm, len: bS.length, oursRepeatUs: oursRepeat, oursFreshUs: oursFresh, shim40Us: shim40, hand40Us: hand40,',
  '    shimUs: shim, handUs: hand,',
  '    vsShimRepeat: shim > 0 ? shim / oursRepeat : 0,',
  '    vsShimFresh: shim40 > 0 ? shim40 / oursFresh : 0,',
  '    vsHandFresh: hand40 > 0 ? hand40 / oursFresh : 0,',
  '    vsHand: hand > 0 ? hand / oursRepeat : 0 };',
  '}',
  'var bCorrect = {};',
  'bCorrect.feff = { ours: ESSTR.trim("\\ufeffq\\ufeff") === "q", shim: bShimTrim("\\ufeffq\\ufeff") === "q", hand: bHandTrim("\\ufeffq\\ufeff") === "q" };',
  'bCorrect.mvsep = { ours: ESSTR.trim("\\u180eq\\u180e") === "\\u180eq\\u180e", shim: bShimTrim("\\u180eq\\u180e") === "\\u180eq\\u180e", hand: bHandTrim("\\u180eq\\u180e") === "\\u180eq\\u180e" };',
  'var bReport = { engine: $.version, host: app.name + " " + app.version, rows: bOut, correct: bCorrect };',
  'bReport;'
].join('\n');
writeFileSync(probePath, probeSrc);

console.log('benchmark: running 4 inputs x 4 impls in Illustrator...');
var pyOut;
try {
  pyOut = execFileSync('python', [TOOL, 'eval', '--file', probePath.replace(/\\/g, '/')], {
    encoding: 'utf8', timeout: 300000
  });
} catch (e) {
  console.error('benchmark: COM tool failed: ' + String((e.stdout || e.message) + '').slice(0, 2000));
  process.exit(1);
}
var env;
try { env = JSON.parse(pyOut.trim()); } catch (e) { console.error('benchmark: tool output not JSON: ' + pyOut.slice(0, 500)); process.exit(1); }
if (!env.ok || !env.result) {
  console.error('benchmark: tool/engine error: ' + JSON.stringify(env).slice(0, 1500));
  process.exit(1);
}
var report = env.result.result || env.result;

console.log('');
console.log('ESSTR live benchmark — ' + report.host + ' / ExtendScript ' + report.engine + ', best-of-9 medians (us):');
console.log('');
console.log('input           len   rep(us)  fresh40(us) shim40(us) hand40(us)  vsShimRep vsShimFresh');
ESARR.forEach(report.rows, function (row) {
  var pad = function (s, w) {
    while (s.length < w) { s = ' ' + s; }
    return s;
  };
  var padN = function (s, w) {
    while (s.length < w) { s = s + ' '; }
    return s;
  };
  console.log(padN(row.name, 14) + pad(String(row.len), 5) + pad(String(row.oursRepeatUs), 8) +
    pad(String(row.oursFreshUs), 11) + pad(String(row.shim40Us), 11) + pad(String(row.hand40Us), 11) +
    '  ' + row.vsShimRepeat.toFixed(2) + 'x' + pad(row.vsShimFresh.toFixed(2), 8) + 'x');
});
console.log('');
console.log('fresh40 lanes time 40 distinct strings (memo-miss dominated): ESSTR vs shim regex vs hand scan.');
console.log('vsShimRep > 1 = ESSTR (repeated string, memo hit) faster than the stock shim regex;');
console.log('vsShimFresh > 1 = ESSTR (40 fresh strings) faster than the stock shim regex;');
console.log('vsHand > 1 = ESSTR faster than the hand-rolled scan.');
console.log('correctness on bench inputs (FEFF must strip, U+180E must stay):');
console.log('  FEFF:   ours=' + report.correct.feff.ours + ' shim=' + report.correct.feff.shim + ' hand=' + report.correct.feff.hand);
console.log('  U+180E: ours=' + report.correct.mvsep.ours + ' shim=' + report.correct.mvsep.shim + ' hand=' + report.correct.mvsep.hand);
